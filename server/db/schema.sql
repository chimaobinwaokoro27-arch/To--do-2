-- ============================================================================
-- TaskFlow — PostgreSQL schema for Supabase
-- ============================================================================
-- This file is a DRAFT for review. Running it does not delete anything and it
-- is safe to run more than once (every statement is idempotent).
--
-- It is intentionally close to the current SQLite schema so application
-- behaviour does not change:
--   * `completed` and `email_sent` stay integer 0/1 (the React UI checks
--     `task.completed === 1` and `task.emailSent === 1`).
--   * Dates stay TEXT in the same "YYYY-MM-DDTHH:mm:ss" local format, because
--     the reminder query compares them with a plain `<=` string comparison.
--
-- Column names are snake_case here. The backend maps every result row back to
-- the camelCase names the API/UI already use (see the migration plan), so the
-- JSON contract is unchanged.
-- ============================================================================

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT     NOT NULL UNIQUE,
  password_hash TEXT     NOT NULL,
  created_at    TEXT     NOT NULL
);

CREATE TABLE IF NOT EXISTS tasks (
  id               INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title            TEXT     NOT NULL,
  description      TEXT,
  deadline         TEXT     NOT NULL,
  reminder_minutes INTEGER  NOT NULL DEFAULT 60,
  reminder_at      TEXT     NOT NULL,
  recipient_email  TEXT     NOT NULL,
  completed        SMALLINT NOT NULL DEFAULT 0,
  email_sent       SMALLINT NOT NULL DEFAULT 0,
  created_at       TEXT     NOT NULL,
  -- Nullable on purpose: tasks created before accounts existed have no owner
  -- and must stay hidden from every user, exactly as in SQLite.
  user_id          INTEGER  REFERENCES users(id)
);

-- Same indexes the SQLite version creates, renamed for snake_case columns.
CREATE INDEX IF NOT EXISTS idx_tasks_user_id      ON tasks (user_id);
CREATE INDEX IF NOT EXISTS idx_tasks_reminder_due ON tasks (email_sent, completed, reminder_at);

-- ----------------------------------------------------------------------------
-- Optional, only if you later copy an old database in: make sure the legacy
-- `user_id` column exists. Harmless on a fresh database.
-- ----------------------------------------------------------------------------
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id);
