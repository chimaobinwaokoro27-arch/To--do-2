import pg from 'pg';

const { Pool } = pg;

// PostgreSQL (Supabase) via environment variables only — never hardcoded.
const connectionString = (process.env.DATABASE_URL || '').trim();
const sslDisabled = (process.env.PGSSL_DISABLE || '').toLowerCase() === 'true';

export const pool = new Pool({
  connectionString: connectionString || undefined,
  // Supabase requires SSL. rejectUnauthorized:false keeps the connection
  // encrypted without needing Supabase's CA certificate on every machine.
  ssl: sslDisabled ? false : { rejectUnauthorized: false },
  max: Number(process.env.PG_POOL_MAX) || 5,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000,
});

pool.on('error', (error) => {
  console.error('Unexpected PostgreSQL pool error:', error?.message || error);
});

/**
 * Converts snake_case column names back to the camelCase names the old
 * SQLite database used, so the JSON the browser receives stays identical
 * (task.reminderAt, task.recipientEmail, user.passwordHash, ...).
 */
export function camelizeRow(row) {
  const out = {};
  for (const [key, value] of Object.entries(row)) {
    out[key.replace(/_([a-z])/g, (_, c) => c.toUpperCase())] = value;
  }
  return out;
}

/**
 * Runs one query and returns { rows, rowCount }. Rows are always camelCased,
 * so no caller can accidentally leak snake_case keys to the frontend.
 */
export async function query(text, params = []) {
  const result = await pool.query(text, params);
  return {
    rows: result.rows.map(camelizeRow),
    rowCount: result.rowCount,
  };
}

// The schema matches the old SQLite tables. Date columns stay TEXT in the same
// "YYYY-MM-DDTHH:mm:ss" local format, and the 0/1 flag columns stay SMALLINT,
// because the reminder query compares dates with '<=' and the UI checks
// `task.completed === 1` and `task.emailSent === 1`.
async function ensureSchema() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email         TEXT    NOT NULL UNIQUE,
      password_hash TEXT    NOT NULL,
      created_at    TEXT    NOT NULL
    )
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS tasks (
      id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title            TEXT    NOT NULL,
      description      TEXT,
      deadline         TEXT    NOT NULL,
      reminder_minutes INTEGER NOT NULL DEFAULT 60,
      reminder_at      TEXT    NOT NULL,
      recipient_email  TEXT    NOT NULL,
      completed        SMALLINT NOT NULL DEFAULT 0,
      email_sent       SMALLINT NOT NULL DEFAULT 0,
      created_at       TEXT    NOT NULL,
      -- Nullable so tasks created before accounts existed stay hidden.
      user_id          INTEGER REFERENCES users(id)
    )
  `);

  await pool.query('CREATE INDEX IF NOT EXISTS idx_tasks_user_id ON tasks (user_id)');
  await pool.query(
    'CREATE INDEX IF NOT EXISTS idx_tasks_reminder_due ON tasks (email_sent, completed, reminder_at)'
  );

  // Mirrors the old SQLite migration: add the ownership column if an older
  // database does not have it. No data is ever deleted.
  await pool.query(
    'ALTER TABLE tasks ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id)'
  );
}

export async function initDatabase() {
  if (!connectionString) {
    console.warn(
      'DATABASE_URL is not set. Add your Supabase connection string to server/.env before starting.'
    );
  }

  await ensureSchema();

  // COUNT(*) is bigint in PostgreSQL and comes back as a string, so cast to int.
  const taskCount = (await pool.query('SELECT COUNT(*)::int AS count FROM tasks')).rows[0].count;
  const userCount = (await pool.query('SELECT COUNT(*)::int AS count FROM users')).rows[0].count;
  const unownedCount = (
    await pool.query('SELECT COUNT(*)::int AS count FROM tasks WHERE user_id IS NULL')
  ).rows[0].count;

  console.log('Database ready (PostgreSQL)');
  console.log(`${taskCount} task(s) stored, ${userCount} user(s) registered`);

  if (unownedCount > 0) {
    console.log(`${unownedCount} older task(s) have no owner and stay hidden from every user`);
  }

  return { taskCount, userCount, unownedCount };
}

export default pool;